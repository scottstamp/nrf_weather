#!/usr/bin/env python3
"""Generate the small 1-bpp bitmap font used by on-device overlays (splash, offline, low battery).

The host renders all weather content; the firmware only needs a handful of
glyphs for its own status messages, so this emits a compact proportional font
for a limited character set.

    python3 scripts/gen_font.py > firmware/src/font_gen.h
"""

import argparse
import sys

from PIL import Image, ImageDraw, ImageFont

CHARS = " !%+-./0123456789:?ABCDEFGHIJKLMNOPQRSTUVWXYZ"
FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--size", type=int, default=20)
    ap.add_argument("--font", default=FONT)
    args = ap.parse_args()

    font = ImageFont.truetype(args.font, args.size)
    ascent, descent = font.getmetrics()
    height = ascent + descent

    glyphs = []
    for ch in CHARS:
        adv = int(round(font.getlength(ch)))
        w = max(adv, 1)
        img = Image.new("1", (w, height), 0)
        d = ImageDraw.Draw(img)
        d.fontmode = "1"  # no anti-aliasing
        d.text((0, 0), ch, fill=1, font=font)
        rb = (w + 7) // 8
        data = bytearray()
        for y in range(height):
            for bx in range(rb):
                b = 0
                for bit in range(8):
                    x = bx * 8 + bit
                    if x < w and img.getpixel((x, y)):
                        b |= 0x80 >> bit
                data.append(b)
        glyphs.append((ch, w, bytes(data)))

    out = sys.stdout
    out.write("/* Generated by scripts/gen_font.py -- do not edit. */\n")
    out.write(f"/* Source: {args.font.rsplit('/', 1)[-1]} {args.size}px (DejaVu license: free, Bitstream Vera derived) */\n")
    out.write("#pragma once\n#include <stdint.h>\n\n")
    out.write(f"#define FONT_HEIGHT {height}\n")
    out.write(f'#define FONT_CHARS "{CHARS}"\n\n')
    out.write("struct font_glyph {\n\tuint8_t width;\n\tuint16_t offset;\n};\n\n")
    out.write("static const uint8_t font_bitmap[] = {\n")
    offsets = []
    off = 0
    for ch, w, data in glyphs:
        offsets.append(off)
        out.write(f"\t/* '{ch}' w={w} */\n\t")
        out.write(", ".join(f"0x{b:02x}" for b in data))
        out.write(",\n")
        off += len(data)
    out.write("};\n\n")
    out.write("static const struct font_glyph font_glyphs[] = {\n")
    for (ch, w, _), o in zip(glyphs, offsets):
        out.write(f"\t{{{w}, {o}}}, /* '{ch}' */\n")
    out.write("};\n")


if __name__ == "__main__":
    main()
